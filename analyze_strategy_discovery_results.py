#!/usr/bin/env python3
"""Summarize targeted scheduler strategy-discovery results.

Input defaults to ``strategy_discovery_results.json`` generated by
``run_strategy_discovery.py``.  The report is intentionally compact and focuses
on whether beam64 found strategies better than analytical, while also flagging
cases where the current beam search is not a reliable reference.
"""

from __future__ import annotations

import argparse
import collections
import json
import statistics
from pathlib import Path
from typing import Any, Callable, Iterable


ROOT = Path(__file__).resolve().parent
DEFAULT_RESULTS = ROOT / "strategy_discovery_results.json"
DEFAULT_REPORT = ROOT / "strategy_discovery_analysis.md"


def load_rows(path: Path) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    payload = json.loads(path.read_text())
    rows = []
    for case in payload["cases"]:
        result = case.get("result", {})
        if result.get("status") != "ok":
            continue
        rows.append({**case, **result})
    return payload.get("meta", {}), rows


def ratio(row: dict[str, Any], field: str) -> float:
    return row[field] / row["compute_only_ideal_cc"]


def diff(row: dict[str, Any]) -> int:
    return int(row["analytical_minus_beam"])


def win_tie_loss(rows: Iterable[dict[str, Any]]) -> tuple[int, int, int]:
    diffs = [diff(row) for row in rows]
    return (
        sum(d > 0 for d in diffs),
        sum(d == 0 for d in diffs),
        sum(d < 0 for d in diffs),
    )


def fmt_ratio(value: float) -> str:
    return f"{value:.6f}"


def group_lines(
    rows: list[dict[str, Any]],
    title: str,
    key_fn: Callable[[dict[str, Any]], Any],
) -> list[str]:
    groups: dict[Any, list[dict[str, Any]]] = collections.defaultdict(list)
    for row in rows:
        groups[key_fn(row)].append(row)

    out = [f"### {title}", "", "| group | n | beam win/tie/loss | avg analytical/ideal | avg beam/ideal | avg diff cc | min diff | max diff |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for key in sorted(groups, key=lambda x: str(x)):
        items = groups[key]
        ds = [diff(row) for row in items]
        wins, ties, losses = win_tie_loss(items)
        out.append(
            "| "
            + " | ".join(
                [
                    str(key),
                    str(len(items)),
                    f"{wins}/{ties}/{losses}",
                    fmt_ratio(statistics.mean(ratio(row, "analytical_cc") for row in items)),
                    fmt_ratio(statistics.mean(ratio(row, "beam_cc") for row in items)),
                    f"{statistics.mean(ds):.1f}",
                    str(min(ds)),
                    str(max(ds)),
                ]
            )
            + " |"
        )
    out.append("")
    return out


def compact_case(row: dict[str, Any]) -> str:
    path = " -> ".join(row.get("beam_path_tags", [])[:6])
    return (
        f"- case {row['case_id']}: diff={diff(row)} cc, "
        f"tokens={row['tokens_sorted']}, cache={row['cache_mode']}, "
        f"A/I={ratio(row, 'analytical_cc'):.4f}, "
        f"B/I={ratio(row, 'beam_cc'):.4f}, path={path}"
    )


def build_report(meta: dict[str, Any], rows: list[dict[str, Any]]) -> str:
    diffs = [diff(row) for row in rows]
    wins, ties, losses = win_tie_loss(rows)
    best_of_ratios = [
        min(row["analytical_cc"], row["beam_cc"]) / row["compute_only_ideal_cc"]
        for row in rows
    ]
    improved = [row for row in rows if row["beam_cc"] < row["analytical_cc"]]

    lines = [
        "# Strategy Discovery Analysis",
        "",
        f"- beam mode: `{meta.get('beam_mode', 'unknown')}`",
        f"- completed cases: {len(rows)} / {meta.get('n_cases', len(rows))}",
        f"- runtime: {meta.get('last_runtime_s', 'unknown')} s",
        f"- diff definition: `analytical_cc - beam_cc`, so positive means beam is faster.",
        "",
        "## Overall",
        "",
        f"- beam better/equal/worse than analytical: {wins}/{ties}/{losses}",
        f"- diff counts: {dict(collections.Counter(diffs).most_common())}",
        f"- avg analytical/ideal: {fmt_ratio(statistics.mean(ratio(row, 'analytical_cc') for row in rows))}",
        f"- avg beam64/ideal: {fmt_ratio(statistics.mean(ratio(row, 'beam_cc') for row in rows))}",
        f"- avg best-of(analytical, beam64)/ideal: {fmt_ratio(statistics.mean(best_of_ratios))}",
        f"- median analytical/ideal: {fmt_ratio(statistics.median(ratio(row, 'analytical_cc') for row in rows))}",
        f"- median beam64/ideal: {fmt_ratio(statistics.median(ratio(row, 'beam_cc') for row in rows))}",
        f"- analytical cases improved by beam64: {len(improved)}",
        "",
        "## Main Interpretation",
        "",
        "- Beam64 found a real missing strategy in 22 cases, always in `cache=none`, usually `hot-hot + medium-medium + tiny`.",
        "- The improvement is always one block of 33792 cc in this suite.",
        "- Beam64 is not yet a safe universal reference: it is worse than analytical in 225 cases, mostly tiny-tail cases where it keeps a tiny-first path.",
        "- For this result set, analytical remains the safer baseline; beam64 is currently more useful as a strategy-discovery tool.",
        "",
        "## Best Beam Wins",
        "",
    ]
    for row in sorted(rows, key=diff, reverse=True)[:12]:
        lines.append(compact_case(row))
    lines.extend(["", "## Worst Beam Losses", ""])
    for row in sorted(rows, key=diff)[:12]:
        lines.append(compact_case(row))
    lines.extend([""])
    lines.extend(group_lines(rows, "By Cache Mode", lambda row: row["cache_mode"]))
    lines.extend(group_lines(rows, "By Variant", lambda row: row["variant"]))
    lines.extend(group_lines(rows, "By Active Expert Count", lambda row: row["active_n"]))
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args()

    meta, rows = load_rows(args.results)
    report = build_report(meta, rows)
    args.report.write_text(report)
    print(f"Wrote {args.report}")
    print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
